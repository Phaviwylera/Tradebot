function costPerShare(price, spread, config) {
  return spread / 2 + price * (config.costBufferPct / 100);
}

export function runRisk(strategyReport, newsReport, scoutReport, chartsReport, context, { config, nowMs } = {}) {
  const { openPositions = [], tradesToday = 0 } = context || {};
  const bankroll = num(context?.bankroll, config.bankroll);
  const decisions = [];
  const checksCommon = [];

  const reportTimes = [scoutReport, newsReport, chartsReport, strategyReport].map(r => ({
    agent: r?.agent,
    ms: r?.timestamp_utc ? Date.parse(r.timestamp_utc) : NaN,
  }));
  const missing = reportTimes.filter(r => !Number.isFinite(r.ms));
  if (missing.length) {
    checksCommon.push({
      name: 'pipeline_complete',
      pass: false,
      detail: `missing timestamp on: ${missing.map(r => r.agent).join(', ')}`,
    });
  } else {
    const oldest = Math.max(...reportTimes.map(r => (nowMs - r.ms) / 60_000));
    checksCommon.push({
      name: 'input_freshness',
      pass: oldest <= config.watchlistFreshnessMinutes,
      detail: `oldest upstream report is ${oldest.toFixed(1)} min old (limit ${config.watchlistFreshnessMinutes})`,
    });
  }
  checksCommon.push({
    name: 'paper_mode',
    pass: config.mode === 'paper' && config.allowLiveOrders === false,
    detail: `mode=${config.mode}, allow_live_orders=${config.allowLiveOrders}`,
  });

  const newsById = new Map(newsReport.evidence.map(e => [e.market_id, e]));
  const approvedSoFar = [];
  let exposure = openPositions.reduce((sum, position) => sum + num(position.notional, 0), 0);
  let riskCommitted = openPositions.reduce((sum, position) => sum + num(position.risk_dollars, 0), 0);
  const categoryCounts = {};
  const eventCounts = {};
  const questionCounts = {};
  const questionKey = text => String(text || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
  for (const position of openPositions) {
    const category = position.category || 'other';
    categoryCounts[category] = (categoryCounts[category] || 0) + 1;
    const eventKey = position.event_id || position.market_id;
    eventCounts[eventKey] = (eventCounts[eventKey] || 0) + 1;
    questionCounts[questionKey(position.question)] = (questionCounts[questionKey(position.question)] || 0) + 1;
  }

  for (const plan of strategyReport.evidence) {
    const checks = checksCommon.map(check => ({ ...check }));
    const reasons = checksCommon.filter(check => !check.pass).map(check => check.detail);
    const push = (name, pass, detail) => {
      checks.push({ name, pass, detail });
      if (!pass) reasons.push(detail);
    };

    push('plan_ready', plan.status === 'plan', plan.status === 'plan' ? 'strategy returned a complete plan' : `strategy returned ${plan.status}: ${plan.reason}`);

    const scout = scoutReport.evidence.find(e => e.market_id === plan.market_id);
    const news = newsById.get(plan.market_id);
    const chart = chartsReport.evidence.find(e => e.market_id === plan.market_id);

    if (plan.status !== 'plan' || !scout || !chart) {
      decisions.push({
        market_id: plan.market_id,
        question: plan.question,
        verdict: 'NOT_REVIEWED',
        checks,
        reasons: reasons.length ? reasons : ['plan did not reach the risk stage'],
      });
      continue;
    }

    const quoteMs = scout.source_timestamp ? Date.parse(scout.source_timestamp) : NaN;
    const quoteAgeMin = Number.isFinite(quoteMs) ? (nowMs - quoteMs) / 60_000 : Infinity;
    push('fresh_quote', quoteAgeMin <= config.chartFreshnessMinutes,
      Number.isFinite(quoteMs)
        ? `quote snapshot is ${quoteAgeMin.toFixed(0)} min old (limit ${config.chartFreshnessMinutes})`
        : 'quote has no source timestamp');
    push('fresh_news', (news?.fresh_count ?? 0) > 0, news?.fresh_count ? `${news.fresh_count} fresh headline(s)` : 'no fresh dated source');
    push('news_required', !config.requireNews || (news?.fresh_count ?? 0) > 0, config.requireNews ? 'desk requires dated news before a plan' : 'news not required by config');
    push('event_risk', news?.event_risk !== 'high', `event risk: ${news?.event_risk || 'unknown'}`);
    push('liquidity', scout.metrics.liquidity >= config.minLiquidity,
      `liquidity ${money(scout.metrics.liquidity)} vs floor ${money(config.minLiquidity)}`);
    push('spread', scout.metrics.spread <= config.maxSpread,
      `spread ${scout.metrics.spread.toFixed(3)} vs limit ${config.maxSpread}`);
    push('history', chart.data_quality.points >= config.minHistoryPoints,
      `${chart.data_quality.points} bars, ${chart.data_quality.span_hours}h span`);
    push('chart_conflicts', (plan.evidence_used?.chart_conflicts || []).length === 0,
      plan.evidence_used?.chart_conflicts?.length
        ? `charts flagged: ${plan.evidence_used.chart_conflicts.join('; ')}`
        : 'no chart conflicts');
    const spread = Math.max(scout.metrics.spread, 0.002);
    const cost = costPerShare(plan.entry, spread, config);
    const netRisk = plan.risk_per_share + cost;
    const netReward = plan.reward_per_share - cost;
    const netRR = netReward > 0 ? netReward / netRisk : 0;

    push('rr_after_costs', plan.gross_rr >= config.minNetRR,
      `gross R:R ${plan.gross_rr.toFixed(2)} vs floor ${config.minNetRR}`);
    push('stop_vs_spread', plan.risk_per_share >= spread,
      `stop distance ${plan.risk_per_share.toFixed(3)} vs spread ${spread.toFixed(3)}; a stop inside the spread is noise`);
    push('entry_within_band', plan.entry_distance <= config.maxEntryDistance,
      `planned entry is ${plan.entry_distance} from the quote (limit ${config.maxEntryDistance})`);
    push('unresolved_disagreements', (plan.disagreements || []).length === 0,
      plan.disagreements?.length ? plan.disagreements.join('; ') : 'agents agree');
    push('net_reward_to_spread', plan.reward_per_share / Math.max(spread, 1e-6) >= config.minRewardToSpread,
      `reward ${plan.reward_per_share.toFixed(3)} is ${(plan.reward_per_share / Math.max(spread, 1e-6)).toFixed(1)}× the spread`);
    push('net_rr', netRR >= config.minNetRR,
      `net R:R ${netRR.toFixed(2)} after ${cost.toFixed(4)}/share of costs vs floor ${config.minNetRR}`);

    // Sizing
    let riskBudget = (bankroll * config.maxPositionRiskPct) / 100;
    if (news?.event_risk === 'medium') riskBudget = riskBudget * (config.eventRiskMedium === 'halve' ? 0.5 : 1);
    const exposureCap = (bankroll * config.maxTotalExposurePct) / 100;
    const remainingExposure = Math.max(0, exposureCap - exposure);
    const dailyRiskCap = (bankroll * config.maxDailyRiskPct) / 100 - riskCommitted;
    riskBudget = Math.min(riskBudget, dailyRiskCap);

    const sharesByRisk = netRisk > 0 ? Math.floor(riskBudget / netRisk) : 0;
    const sharesByExposure = plan.entry > 0 ? Math.floor(remainingExposure / plan.entry) : 0;
    const liquidityCap = Math.max(0, scout.metrics.liquidity * 0.01);
    const sharesByLiquidity = plan.entry > 0 ? Math.floor(liquidityCap / plan.entry) : 0;
    const shares = Math.max(0, Math.min(sharesByRisk, sharesByExposure, sharesByLiquidity));

    push('size', shares >= 1, shares >= 1
      ? `${shares} share(s)`
      : `size rounds to zero (risk budget ${money(Math.max(riskBudget, 0))}, exposure left ${money(remainingExposure)})`);
    const minShares = num(scout.order_min_size, 1);
    push('order_minimum', shares >= minShares,
      `${shares} share(s) vs exchange minimum ${minShares}`);
    push('position_cap', openPositions.length + approvedSoFar.length < config.maxPositions,
      `${openPositions.length + approvedSoFar.length} of ${config.maxPositions} position slots used`);

    const category = scout.category || 'other';
    push('category_concentration', (categoryCounts[category] || 0) < config.maxPerCategory,
      `${categoryCounts[category] || 0} of ${config.maxPerCategory} allowed ${category} positions`);
    const eventKey = scout.event_id || plan.market_id;
    push('event_concentration', (eventCounts[eventKey] || 0) < config.maxPerEvent,
      `${eventCounts[eventKey] || 0} of ${config.maxPerEvent} allowed positions on this event`);
    push('duplicate_question', (questionCounts[questionKey(plan.question)] || 0) === 0,
      'same question is already in the book or approved in this run');

    const failed = checks.filter(c => !c.pass);
    let verdict = failed.length ? 'REJECTED' : 'PASSED';
    if (verdict === 'PASSED' && news?.event_risk === 'medium') verdict = 'REDUCED';

    if (verdict === 'PASSED' || verdict === 'REDUCED') {
      const notional = round(shares * plan.entry, 2);
      const riskDollars = round(shares * plan.risk_per_share, 2);
      exposure += notional;
      riskCommitted += riskDollars;
      categoryCounts[category] = (categoryCounts[category] || 0) + 1;
      eventCounts[eventKey] = (eventCounts[eventKey] || 0) + 1;
      questionCounts[questionKey(plan.question)] = (questionCounts[questionKey(plan.question)] || 0) + 1;
      approvedSoFar.push(plan.market_id);
      decisions.push({
        market_id: plan.market_id,
        question: plan.question,
        url: plan.url,
        side: plan.side,
        category,
        event_id: eventKey,
        verdict,
        checks,
        reasons: [],
        risk_notes: verdict === 'REDUCED' ? ['size halved for medium event risk'] : [],
        size: {
          shares,
          entry: plan.entry,
          notional,
          risk_dollars: riskDollars,
          max_loss_pct_of_bankroll: round((riskDollars / bankroll) * 100, 2),
          net_rr: round(netRR, 2),
          cost_per_share: round(cost, 4),
          exposure_after: round(exposure, 2),
          exposure_limit: round(exposureCap, 2),
        },
        plan,
      });
    } else {
      decisions.push({
        market_id: plan.market_id,
        question: plan.question,
        url: plan.url,
        side: plan.side,
        category,
        event_id: eventKey,
        verdict,
        checks,
        reasons,
        failed_checks: failed.map(c => c.name),
        plan,
      });
    }
  }

  const passed = decisions.filter(d => d.verdict === 'PASSED' || d.verdict === 'REDUCED');
  const rejected = decisions.filter(d => d.verdict === 'REJECTED');
  const reviewed = decisions.filter(d => d.verdict !== 'NOT_REVIEWED');
  const status = decisions.length ? 'complete' : 'needs_data';

  const summary = decisions.length
    ? `${passed.length} plan(s) cleared the risk gate, ${rejected.length} rejected, ${decisions.length - reviewed.length} never reached it.`
    : 'No plans reached the risk agent.';

  const risks = [];
  if (!passed.length) risks.push('Risk vetoed the whole board: nothing is cleared for a paper entry.');
  for (const d of rejected) risks.push(`Rejected ${d.side || 'plan'} on "${d.question}": ${d.reasons[0] || 'failed check'}`);

  return baseReport(
    'risk',
    nowMs,
    status,
    summary,
    decisions,
    risks,
    'Boss agent: confirm every stage, then approve, wait or reject.',
    {
      bankroll: round(bankroll, 2),
      exposure_limit: round((bankroll * config.maxTotalExposurePct) / 100, 2),
      exposure_used: round(exposure, 2),
      risk_committed: round(riskCommitted, 2),
      open_positions: openPositions.length,
      trades_today: tradesToday,
      passed: passed.length,
      rejected: rejected.length,
      common_checks: checksCommon,
      limits: {
        max_positions: config.maxPositions,
        max_total_exposure_pct: config.maxTotalExposurePct,
        max_position_risk_pct: config.maxPositionRiskPct,
        max_daily_risk_pct: config.maxDailyRiskPct,
        max_per_category: config.maxPerCategory,
        max_per_event: config.maxPerEvent,
        min_net_rr: config.minNetRR,
      },
      policy:
        'The gate never relaxes a rule to make a plan pass. Sizes are the smaller of the risk budget, ' +
        'the remaining exposure cap and 1% of quoted liquidity. A failed check is a veto.',
    },
  );
}

