function chooseView(chart) {
  const { primary, secondary } = chart.views;
  if (primary.trend === 'up' && secondary.trend === 'down') return 'primary';
  if (primary.trend === 'down' && secondary.trend === 'up') return 'secondary';
  if (primary.structure_break === 'up') return 'primary';
  if (secondary.structure_break === 'up') return 'secondary';
  return null;
}

function nearestSupportBelow(levels, price) {
  const list = levels.filter(level => level < price).sort((a, b) => b - a);
  return list.length ? list[0] : null;
}

function nearestResistanceAbove(levels, price) {
  const list = levels.filter(level => level > price).sort((a, b) => a - b);
  return list.length ? list[0] : null;
}

export function runStrategy(scoutReport, newsReport, chartsReport, { config, nowMs } = {}) {
  const newsById = new Map(newsReport.evidence.map(e => [e.market_id, e]));
  const scoutById = new Map(scoutReport.evidence.map(e => [e.market_id, e]));
  const plans = [];

  for (const chart of chartsReport.evidence) {
    if (chart.status !== 'complete') continue;
    const scout = scoutById.get(chart.market_id);
    const news = newsById.get(chart.market_id);
    const reasons = [];
    const disagreements = [];

    if (config.requireNews && !news?.fresh_count) {
      reasons.push('no fresh dated source; desk rule requires news before a plan');
    }
    if (news?.event_risk === 'high') reasons.push('high event risk');
    if (news?.flags?.includes('LOW_RELEVANCE')) reasons.push('headline set does not clearly match the question');

    const sideKey = chooseView(chart);
    const view = sideKey ? chart.views[sideKey] : null;
    const sideLabel = sideKey === 'primary' ? chart.primary_outcome : chart.secondary_outcome;

    if (!sideKey || !view) {
      plans.push({
        market_id: chart.market_id,
        question: chart.question,
        status: 'WAIT',
        reason: reasons.length ? reasons.join('; ') : 'no directional trend or confirmed structure break',
        trend: chart.views.primary.trend,
        disagreements,
      });
      continue;
    }

    const directNews = (news?.direct_count ?? 0) >= 2;
    if (directNews && news?.tone === 'cautious' && view.trend === 'up') {
      disagreements.push('headline tone is cautious while the trade direction is up');
    }
    if (directNews && news?.tone === 'constructive' && view.trend === 'down') {
      disagreements.push('headline tone is constructive while the trade direction is down');
    }
    if (news?.event_risk === 'medium') reasons.push('medium event risk');
    if (chart.conflicts.length) disagreements.push(...chart.conflicts);
    if (view.atr_pct > 0.12) reasons.push(`average bar range ${pct(view.atr_pct, 1)} is too noisy for a fixed stop`);

    const price = view.last;
    const atr = Math.max(view.atr, 0.002);
    const quote = round(clamp(sideKey === 'primary'
      ? (scout?.price ?? price) + (scout?.metrics.spread ?? 0) / 2
      : 1 - ((scout?.price ?? price) - (scout?.metrics.spread ?? 0) / 2), 0.01, 0.98), 3);

    const supportLevel = nearestSupportBelow(view.levels.all_strong.map(level => level.level), price);
    const resistanceLevel = nearestResistanceAbove(view.levels.all_strong.map(level => level.level), price);
    const structure = view.structure_break;
    const extended = view.extended_up;

    let entryType;
    let trigger;
    let entry;
    let entryZone;

    // The level that was actually broken is the prior 1-hour range high, not the next
    // resistance above the current price (that would be a chase, not a breakout rule).
    const brokenLevel = view.prior_high ?? view.window_max;

    if (structure === 'up') {
      if (extended) {
        entryType = 'breakout_retest';
        entry = round(clamp(brokenLevel + atr * 0.25, 0.01, 0.975), 3);
        entryZone = [
          round(clamp(brokenLevel - atr * 0.25, 0.005, 0.97), 3),
          round(clamp(brokenLevel + atr * 0.5, 0.01, 0.98), 3),
        ];
        trigger = `retest of ${brokenLevel.toFixed(3)} holds after the structure break`;
      } else {
        entryType = 'breakout';
        entry = quote;
        entryZone = [
          round(clamp(brokenLevel, 0.005, 0.97), 3),
          round(clamp(entry + atr * 0.5, 0.01, 0.98), 3),
        ];
        trigger = `quote holds above ${brokenLevel.toFixed(3)} with the break intact`;
      }
    } else if (view.trend === 'up') {
      entryType = 'pullback';
      const support = supportLevel ?? Math.max(price - atr * 1.5, view.window_min);
      entry = round(clamp(support + atr * 0.25, 0.005, 0.97), 3);
      entryZone = [
        round(clamp(support, 0.005, 0.97), 3),
        round(clamp(support + atr, 0.01, 0.98), 3),
      ];
      trigger = `price pulls back into ${support.toFixed(3)}-${(support + atr).toFixed(3)} and holds`;
    } else {
      entryType = 'reversal';
      const reclaim = Math.min(view.window_max, quote + atr);
      entry = round(clamp(reclaim + atr * 0.25, 0.005, 0.975), 3);
      entryZone = [
        round(clamp(reclaim, 0.005, 0.97), 3),
        round(clamp(reclaim + atr, 0.01, 0.98), 3),
      ];
      trigger = `price reclaims ${reclaim.toFixed(3)} and momentum stays positive`;
    }

    if (extended && structure !== 'up') {
      reasons.push('price is stretched above its recent mean; wait for a pullback');
    }

    const minGap = Math.max(atr * 0.5, 0.006);
    let invalidation;
    if (entryType === 'breakout_retest') {
      invalidation = round(clamp(brokenLevel - atr * 0.75, 0.005, entry - 0.005), 3);
    } else {
      const stopCandidates = [
        Number.isFinite(supportLevel) ? supportLevel - atr * 0.25 : NaN,
        Number.isFinite(view.recent_low) ? view.recent_low - atr * 0.25 : NaN,
        entry - atr * 2,
      ].filter(level => Number.isFinite(level) && level <= entry - minGap);
      invalidation = stopCandidates.length ? Math.max(...stopCandidates) : entry - atr * 2;
      invalidation = round(clamp(invalidation, 0.005, entry - 0.005), 3);
    }

    const floorTarget = entry + Math.max(atr * 4, 0.05);
    const levelTarget = resistanceLevel && resistanceLevel > entry + 0.008 ? resistanceLevel : NaN;
    let target = Math.max(floorTarget, Number.isFinite(levelTarget) ? levelTarget : 0);
    target = round(clamp(target, entry + 0.01, 0.985), 3);

    if (extended && structure === 'up') {
      reasons.push('extended breakout: the plan waits for a retest instead of chasing');
    }
    if (entryType === 'pullback' && quote - entry > config.maxPullbackDistance) {
      reasons.push(`pullback entry is ${(quote - entry).toFixed(3)} below the quote, beyond the ${config.maxPullbackDistance} limit`);
    }
    if ((entryType === 'pullback' || entryType === 'breakout_retest') && entry >= quote) {
      reasons.push('conditional entry is not below the current quote');
    }
    if (target <= quote + 0.005) {
      reasons.push(`target ${target.toFixed(3)} is not above the current quote ${quote.toFixed(3)}; the move may already be priced`);
    }
    if (entry - invalidation > config.maxStopDistance) {
      reasons.push(`stop distance ${(entry - invalidation).toFixed(3)} exceeds the ${config.maxStopDistance} limit`);
    }
    if (entry <= invalidation) reasons.push('entry is not above invalidation');
    if (Math.abs(entry - quote) > config.maxEntryDistance) {
      reasons.push(`entry ${entry.toFixed(3)} is more than ${config.maxEntryDistance} away from the quote ${quote.toFixed(3)}`);
    }

    const riskPerShare = round(entry - invalidation, 4);
    const rewardPerShare = round(target - entry, 4);
    const rr = riskPerShare > 0 ? round(rewardPerShare / riskPerShare, 2) : 0;
    if (rr < config.minNetRR) reasons.push(`gross reward:risk ${rr.toFixed(2)} below ${config.minNetRR}`);

    const marketEndMs = scout?.ends_at ? Date.parse(scout.ends_at) : NaN;
    const sixHours = nowMs + 6 * 3_600_000;
    const timeLimitMs = Number.isFinite(marketEndMs)
      ? Math.min(sixHours, marketEndMs - config.minMinutesToResolution * 60_000)
      : sixHours;

    const neutralTone = !news?.tone || ['neutral', 'not_applicable', 'unknown'].includes(news.tone);
    const confidenceParts = [
      view.trend !== 'range' ? 25 : 0,
      structure ? 20 : 0,
      view.atr_pct < 0.06 ? 15 : 5,
      (scout?.metrics.z_volume ?? 0) > 1 ? 15 : 5,
      news?.fresh_count ? 15 : 0,
      neutralTone ? 10 : ((news.tone === 'constructive') === (view.trend === 'up') ? 10 : 0),
    ];
    const confidence = Math.round(clamp(confidenceParts.reduce((a, b) => a + b, 0), 0, 100));

    const status = reasons.length ? 'WAIT' : 'plan';

    plans.push({
      market_id: chart.market_id,
      question: chart.question,
      url: scout?.url || '',
      status,
      reason: reasons.length ? reasons.join('; ') : null,
      side_key: sideKey,
      side: sideLabel,
      side_index: sideKey === 'primary' ? 0 : 1,
      entry_type: entryType,
      entry: status === 'plan' ? entry : null,
      quote,
      entry_distance: round(Math.abs(entry - quote), 3),
      entry_zone: entryZone,
      entry_trigger: trigger,
      invalidation: status === 'plan' ? invalidation : null,
      target: status === 'plan' ? target : null,
      risk_per_share: status === 'plan' ? riskPerShare : null,
      reward_per_share: status === 'plan' ? rewardPerShare : null,
      gross_rr: rr,
      time_limit_utc: iso(timeLimitMs),
      confidence,
      evidence_used: {
        scout_score: scout?.score ?? null,
        scout_reasons: scout?.reasons ?? [],
        chart_trend: view.trend,
        chart_levels: view.levels,
        chart_conflicts: view.conflicts,
        chart_warnings: chart.warnings ?? [],
        news_sources: news?.sources ?? [],
        news_direct_count: news?.direct_count ?? 0,
        news_tone: news?.tone ?? 'unknown',
        news_count: news?.fresh_count ?? 0,
        event_risk: news?.event_risk ?? 'unknown',
      },
      disagreements,
    });
  }

  const candidates = plans.filter(p => p.status === 'plan');
  const status = plans.length ? 'complete' : 'needs_data';
  const summary = plans.length
    ? `Wrote ${candidates.length} rule-based plan(s) from ${plans.length} reviewed markets; ${plans.length - candidates.length} returned WAIT.`
    : 'No chart-reviewed market reached the strategy stage.';

  return baseReport(
    'strategy',
    nowMs,
    status,
    summary,
    plans,
    candidates.length ? [] : ['Every candidate returned WAIT; no plan was forced.'],
    'Risk agent: size or veto each plan.',
    {
      reviewed: plans.length,
      plans: candidates.length,
      waits: plans.length - candidates.length,
      policy:
        'A plan exists only when trend and structure agree, the stop is inside the max distance, ' +
        'and reward:risk clears the configured floor. Strategy never sizes a position and never places an order.',
    },
  );
}

