const POSITIVE_WORDS = /\b(beat|beats|surge|surges|rally|rallies|approve|approved|approves|pass|passes|passed|win|wins|won|above|record|upgrade|upgraded|strong|boost|boosts|deal|agreement|confirmed|cleared|advance|advances)\b/gi;
const NEGATIVE_WORDS = /\b(miss|misses|drop|drops|fall|falls|fell|reject|rejected|fails|failed|below|downgrade|downgraded|weak|halts|halted|delay|delayed|probe|lawsuit|cut|cuts|slump|slumps|crash|crashes)\b/gi;
const SPECULATION_WORDS = /\b(may|might|could|reportedly|rumou?r|speculat\w*|expected|analysts?|forecast|likely|unconfirmed|sources say)\b/i;
const EVENT_RISK_WORDS = /\b(fomc|cpi|nfp|payrolls|election|vote|verdict|hearing|rate decision|earnings|kickoff|halftime|final whistle|scheduled|deadline|auction)\b/i;

function toneOf(text) {
  const positives = (text.match(POSITIVE_WORDS) || []).length;
  const negatives = (text.match(NEGATIVE_WORDS) || []).length;
  if (positives > negatives) return { tone: 'constructive', positives, negatives };
  if (negatives > positives) return { tone: 'cautious', positives, negatives };
  return { tone: 'neutral', positives, negatives };
}

export async function runNews(scoutReport, dataLayer, { config, nowMs, onMarket } = {}) {
  const evidence = [];
  const risks = [];
  const perMarket = {};
  let fetched = 0;
  let failed = 0;
  let marketsWithSources = 0;

  for (const item of scoutReport.evidence) {
    const market = dataLayer.getMarketById?.(item.market_id);
    fetched += 1;
    if (!market) {
      failed += 1;
      risks.push(`Market ${item.market_id} disappeared from the scanned universe before the news pass.`);
      continue;
    }
    let headlines = [];
    let error = null;
    try {
      headlines = await dataLayer.getNews(market);
    } catch (e) {
      error = e.message;
    }
    if (error) failed += 1;

    const query = buildNewsQuery(market);
    const queryTokens = new Set(query.toLowerCase().split(/\s+/).filter(Boolean));
    const seenTitles = new Set();
    const items = [];

    for (const headline of headlines) {
      const title = String(headline.title || '').trim();
      if (!title) continue;
      const normalised = title.toLowerCase().replace(/\s+/g, ' ');
      const duplicate = seenTitles.has(normalised);
      seenTitles.add(normalised);
      const publishedMs = headline.publishedMs ?? (headline.publishedAtIso ? Date.parse(headline.publishedAtIso) : NaN);
      const ageHours = Number.isFinite(publishedMs) ? hoursBetween(nowMs, publishedMs) : null;
      const words = new Set(title.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter(Boolean));
      const overlap = [...queryTokens].filter(token => words.has(token)).length;
      const reference = headline.source || 'unattributed';
      const speculation = SPECULATION_WORDS.test(title);

      items.push({
        title,
        link: headline.link || '',
        source: reference,
        source_url: headline.sourceUrl || '',
        published_at: Number.isFinite(publishedMs) ? iso(publishedMs) : null,
        age_hours: ageHours === null ? null : round(ageHours, 1),
        stale: ageHours !== null ? ageHours > config.maxHeadlineAgeHours : true,
        speculative: speculation,
        duplicate,
        query_overlap: overlap,
        relevance: market.synthetic
          ? 'pooled'
          : overlap >= 2 ? 'direct' : overlap === 1 ? 'partial' : 'unclear',
        tone: toneOf(title).tone,
        ...(headline.synthetic ? { synthetic: true } : {}),
      });
    }

    const usable = items.filter(i => !i.duplicate);
    const fresh = usable.filter(i => !i.stale);
    const direct = usable.filter(i => i.relevance === 'direct');
    const sources = [...new Set(usable.map(i => i.source))];
    const tones = { constructive: 0, cautious: 0, neutral: 0 };
    for (const i of usable) tones[i.tone] += 1;
    const keywordTone = tones.constructive > tones.cautious
      ? 'constructive'
      : tones.cautious > tones.constructive
        ? 'cautious'
        : 'neutral';
    const yesNoMarket = /^(yes|no)$/i.test(market.outcomes[0] || '');
    // Pooled test headlines and team-vs-team outcomes have no meaningful keyword polarity.
    const tone = market.synthetic || !yesNoMarket ? 'not_applicable' : keywordTone;

    const eventRisk = (() => {
      if (market.demoEventRisk && market.synthetic) return market.demoEventRisk;
      if (market.category === 'econ' || market.category === 'politics') return 'medium';
      if (usable.some(i => EVENT_RISK_WORDS.test(i.title))) return 'medium';
      return market.synthetic ? 'low' : 'unknown';
    })();

    const flags = [];
    if (!usable.length) flags.push('NO_SOURCES');
    if (usable.length && !fresh.length) flags.push('STALE_ONLY');
    if (items.some(i => i.duplicate)) flags.push('DUPLICATES_REMOVED');
    if (market.synthetic) flags.push('SYNTHETIC_HEADLINES');
    if (!market.synthetic && usable.length && !direct.length) flags.push('LOW_RELEVANCE');
    if (!Number.isFinite(market.endMs)) flags.push('NO_RESOLUTION_DATE');

    if (usable.length) marketsWithSources += 1;
    if (usable.length && fresh.length) {
      evidence.push({
        market_id: market.id,
        question: market.question,
        query,
        source_count: sources.length,
        sources,
        headline_count: usable.length,
        fresh_count: fresh.length,
        direct_count: direct.length,
        tone,
        keyword_tone: keywordTone,
        tone_counts: tones,
        direction_basis: market.synthetic
          ? 'not used for rules: synthetic pooled headlines have no real polarity'
          : 'keyword polarity applied to the first outcome label; may not fit inverted questions',
        event_risk: eventRisk,
        flags,
        items,
      });
    } else {
      evidence.push({
        market_id: market.id,
        question: market.question,
        query,
        source_count: 0,
        sources: [],
        headline_count: 0,
        fresh_count: 0,
        direct_count: 0,
        tone: 'unknown',
        keyword_tone: keywordTone,
        tone_counts: tones,
        event_risk: eventRisk,
        flags,
        items,
        error,
      });
      risks.push(`No usable dated sources for "${market.question}".`);
    }
    perMarket[market.id] = { usable: usable.length, fresh: fresh.length, tones, eventRisk, flags };
    onMarket?.({ marketId: market.id, usable: usable.length });
  }

  const coveredIds = evidence.filter(e => e.fresh_count > 0).map(e => e.market_id);
  let status = 'complete';
  if (!scoutReport.evidence.length) status = 'needs_data';
  else if (!marketsWithSources) status = 'needs_data';
  else if (failed === fetched) status = 'needs_data';

  const summary = scoutReport.evidence.length
    ? `Checked sources for ${fetched} watchlist markets; ${marketsWithSources} have at least one usable headline.`
    : 'No watchlist supplied, so no news could be checked.';

  if (!coveredIds.length) risks.push('No watchlist market has a fresh, dated source.');
  if (config.requireNews) {
    risks.push('Desk rule: a trade plan requires at least one fresh source. Markets with NO_SOURCES are dropped by Strategy.');
  }

  return baseReport(
    'news',
    nowMs,
    status,
    summary,
    evidence,
    risks,
    'Charts agent: review the price series for the markets that carry sources.',
    {
      fetched,
      failed,
      markets_with_sources: marketsWithSources,
      covered_market_ids: coveredIds,
      headline_policy:
        'Headlines are claims, not verified facts. Items are flagged speculative when they use words like may, ' +
        'reportedly or analysts expect. No article is summarised beyond its title, so no detail is invented.',
      require_news: config.requireNews,
    },
  );
}

