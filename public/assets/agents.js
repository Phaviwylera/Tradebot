export async function runDesk({
  dataLayer,
  config = DEFAULT_CONFIG,
  now = () => Date.now(),
  historyLimit = 10,
  context = {},
  onStage = () => {},
  onProgress = () => {},
} = {}) {
  const startedMs = now();
  const runId = newRunId(startedMs, dataLayer.mode);
  const reports = {};
  const histories = {};
  let haltedAt = null;

  const universe = await dataLayer.getUniverse({
    maxScan: config.maxScan,
    onProgress: progress => onProgress({ stage: 'universe', ...progress }),
  });

  reports.scout = runScout(universe, { config, nowMs: now() });
  onStage({ stage: 'scout', report: reports.scout });
  if (reports.scout.status !== 'complete') haltedAt = 'scout';

  if (!haltedAt) {
    reports.news = await runNews(reports.scout, dataLayer, {
      config,
      nowMs: now(),
      onMarket: ({ marketId, usable }) => onProgress({ stage: 'news', marketId, usable }),
    });
    onStage({ stage: 'news', report: reports.news });
    if (reports.news.status !== 'complete') haltedAt = 'news';
  }

  if (!haltedAt) {
    const ids = reports.news.meta.covered_market_ids.slice(0, historyLimit);
    for (const marketId of ids) {
      const market = dataLayer.getMarketById(marketId);
      try {
        histories[marketId] = await dataLayer.getSeries(market);
      } catch (error) {
        histories[marketId] = { points: [], error: error.message };
      }
      onProgress({ stage: 'charts', marketId, done: true });
    }
    reports.charts = runCharts(reports.scout, reports.news, histories, { config, nowMs: now() });
    onStage({ stage: 'charts', report: reports.charts });
    if (reports.charts.status !== 'complete') haltedAt = 'charts';
  }

  if (!haltedAt) {
    reports.strategy = runStrategy(reports.scout, reports.news, reports.charts, { config, nowMs: now() });
    onStage({ stage: 'strategy', report: reports.strategy });
    if (reports.strategy.status !== 'complete') haltedAt = 'strategy';
  }

  if (!haltedAt) {
    reports.risk = runRisk(reports.strategy, reports.news, reports.scout, reports.charts, context, { config, nowMs: now() });
    onStage({ stage: 'risk', report: reports.risk });
    if (reports.risk.status !== 'complete') haltedAt = 'risk';
  }

  reports.boss = runBoss(reports, {
    config,
    nowMs: now(),
    haltedAt,
    runMode: dataLayer.mode,
  });
  onStage({ stage: 'boss', report: reports.boss });

  const finishedMs = now();
  return {
    run_id: runId,
    desk_version: DESK_VERSION,
    mode: dataLayer.mode,
    source: dataLayer.sourceLabel,
    source_detail: universe.note,
    started_utc: iso(startedMs),
    finished_utc: iso(finishedMs),
    duration_ms: finishedMs - startedMs,
    universe: {
      size: universe.markets.length,
      fetched_at: universe.fetchedAt,
      synthetic: universe.markets.some(m => m.synthetic),
    },
    config: { ...config },
    reports,
    halted_at: haltedAt,
    boss: reports.boss,
  };
}

