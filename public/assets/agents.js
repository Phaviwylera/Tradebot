/*
 * agents.js — the six-agent desk.
 *
 * SCOUT    finds unusual markets, never picks a trade.
 * NEWS     reads headlines attached to the watchlist, separates claims from speculation.
 * CHARTS   reads trend, momentum, volume and levels on the outcome series.
 * STRATEGY writes one rule-based plan per candidate. No plan, no trade.
 * RISK     may veto any plan. Its limits are hard-coded defaults, not prompts.
 * BOSS     checks the whole desk and returns APPROVE_FOR_PAPER_TEST / WAIT / REJECT.
 *
 * All six agents are deterministic functions. Every number here is calculated from
 * supplied data. Nothing is generated by a language model, so nothing can be invented.
 * Where data is missing the report says needs_data instead of filling the gap.
 */

