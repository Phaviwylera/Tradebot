const REQUIRED_AGENTS = ['scout', 'news', 'charts', 'strategy', 'risk'];

export function runBoss(reports, { config, nowMs, haltedAt = null, runMode = 'live' } = {}) {
  const missing = REQUIRED_AGENTS.filter(name => !reports[name]);
  const incomplete = REQUIRED_AGENTS.filter(name => reports[name] && reports[name].status !== 'complete');
  const integrity = [];
  const addCheck = (name, pass, detail) => integrity.push({ name, pass, detail });

  addCheck('pipeline_present', missing.length === 0, missing.length ? `missing report(s): ${missing.join(', ')}` : 'all six stages reported');
  addCheck('stages_complete', incomplete.length === 0, incomplete.length ? `incomplete stage(s): ${incomplete.map(n => `${n} (${reports[n].status})`).join(', ')}` : 'every stage returned complete');
  addCheck('paper_only', config.mode === 'paper' && config.allowLiveOrders === false, `mode=${config.mode}, live orders=${config.allowLiveOrders}`);
  addCheck('timestamps', REQUIRED_AGENTS.every(n => reports[n]?.timestamp_utc && Number.isFinite(Date.parse(reports[n].timestamp_utc))), 'every report carries an ISO timestamp');

  const risk = reports.risk;
  const passed = risk ? risk.evidence.filter(d => d.verdict === 'PASSED' || d.verdict === 'REDUCED') : [];
  const rejected = risk ? risk.evidence.filter(d => d.verdict === 'REJECTED') : [];
  const strategy = reports.strategy;
  const plans = strategy ? strategy.evidence.filter(p => p.status === 'plan') : [];
  const waits = strategy ? strategy.evidence.filter(p => p.status === 'WAIT') : [];

  const disagreements = [];
  for (const plan of plans) {
    for (const item of plan.disagreements || []) disagreements.push(`${plan.question}: ${item}`);
  }
  const clean = passed.filter(d => !(d.plan?.disagreements || []).length);

  addCheck('risk_gate_exists', Boolean(risk), risk ? `${risk.evidence.length} plan(s) reviewed by risk` : 'no risk report');
  addCheck('risk_not_blanket_veto', passed.length > 0, passed.length ? `${passed.length} plan(s) cleared` : 'risk cleared nothing');

  let decision;
  let explanation;
  if (missing.length) {
    decision = BOSS_DECISIONS.REJECT;
    explanation = `Rejected: the desk is incomplete (${missing.join(', ')}). A decision cannot be made on a partial pipeline.`;
  } else if (haltedAt) {
    decision = BOSS_DECISIONS.WAIT;
    explanation = `Halted at ${haltedAt.toUpperCase()} because a stage returned needs_data. No trade is approved.`;
  } else if (!clean.length) {
    if (passed.length) {
      decision = BOSS_DECISIONS.WAIT;
      explanation = `${passed.length} plan(s) cleared risk but every one carries an unresolved disagreement. Waiting rather than averaging the conflict.`;
    } else if (rejected.length) {
      decision = BOSS_DECISIONS.REJECT;
      explanation = `Risk rejected every plan (${rejected.length}). No paper entry is authorised.`;
    } else if (plans.length === 0 && waits.length) {
      decision = BOSS_DECISIONS.WAIT;
      explanation = `Strategy returned WAIT on all ${waits.length} reviewed market(s). No setup met the rules.`;
    } else if (!risk.evidence.length) {
      decision = BOSS_DECISIONS.WAIT;
      explanation = 'No plan reached the risk gate, so there is nothing to approve.';
    } else {
      decision = BOSS_DECISIONS.WAIT;
      explanation = 'Nothing cleared the board. Waiting for a complete setup.';
    }
  } else {
    decision = BOSS_DECISIONS.APPROVE;
    explanation = `${clean.length} plan(s) passed every stage with no unresolved disagreement. Approved for paper testing only.`;
  }

  const approved = decision === BOSS_DECISIONS.APPROVE ? clean.map(d => ({
    market_id: d.market_id,
    question: d.question,
    url: d.url,
    side: d.side,
    category: d.category,
    event_id: d.event_id,
    entry: d.plan.entry,
    invalidation: d.plan.invalidation,
    target: d.plan.target,
    time_limit_utc: d.plan.time_limit_utc,
    shares: d.size.shares,
    notional: d.size.notional,
    risk_dollars: d.size.risk_dollars,
    net_rr: d.size.net_rr,
    confidence: d.plan.confidence,
    evidence_used: d.plan.evidence_used,
  })) : [];

  return baseReport(
    'boss',
    nowMs,
    'complete',
    explanation,
    approved,
    missing.length || incomplete.length ? [`missing/incomplete: ${[...missing, ...incomplete].join(', ')}`] : [],
    decision === BOSS_DECISIONS.WAIT
      ? 'Re-run when the next data refresh lands, or when the conflicting evidence resolves.'
      : decision === BOSS_DECISIONS.REJECT
        ? 'Review the failed check names, not the price. Do not loosen limits to force a trade.'
        : 'Log the entry, invalidation, target and time limit in the paper journal before the result is known.',
    {
      decision,
      approved,
      held: decision === BOSS_DECISIONS.APPROVE ? [] : passed,
      integrity,
      disagreements,
      counts: {
        plans: plans.length,
        waits: waits.length,
        risk_passed: passed.length,
        risk_rejected: rejected.length,
        missing_reports: missing,
        incomplete_reports: incomplete,
      },
      data_source: runMode === 'test' ? 'SYNTHETIC TEST DATA' : 'live public market data',
      final_word:
        'Paper only. No order endpoint exists in this project. Manual human approval is required before any action.',
    },
  );
}

