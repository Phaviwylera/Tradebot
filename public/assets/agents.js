function categoryStats(markets) {
  const byCategory = new Map();
  for (const market of markets) {
    if (!byCategory.has(market.category)) byCategory.set(market.category, []);
    byCategory.get(market.category).push(market);
  }
  const stats = new Map();
  for (const [category, list] of byCategory) {
    stats.set(category, {
      count: list.length,
      medianVolume: median(list.map(m => m.volume24h).filter(v => v > 0)),
      medianLiquidity: median(list.map(m => m.liquidity).filter(v => v > 0)),
      medianMove1h: median(list.map(m => Math.abs(m.move1h))),
      medianMove24h: median(list.map(m => Math.abs(m.move24h))),
      logVolumes: list.map(m => Math.log1p(Math.max(m.volume24h, 0))),
      absMoves1h: list.map(m => Math.abs(m.move1h)),
      absMoves24h: list.map(m => Math.abs(m.move24h)),
    });
  }
  return stats;
}

function describeMarketQuality(market, config, nowMs) {
  const reasons = [];
  const hasQuote = market.hasQuote === true && Number.isFinite(market.spread);
  const spreadPct = hasQuote && market.price > 0 ? market.spread / market.price : 1;
  if (!market.acceptingOrders) reasons.push('not accepting orders');
  if (market.closed) reasons.push('market is closed');
  if (market.enableOrderBook === false) reasons.push('no order book enabled');
  if (!market.tokens?.[0] || !market.tokens?.[1]) reasons.push('missing CLOB token ids');
  if (!hasQuote) reasons.push('no two-sided quote in the feed');
  if (market.liquidity < config.minLiquidity) {
    reasons.push(`liquidity ${money(market.liquidity)} below floor ${money(config.minLiquidity)}`);
  }
  if (hasQuote && market.spread > config.maxSpread) {
    reasons.push(`spread ${market.spread.toFixed(3)} wider than ${config.maxSpread}`);
  }
  if (hasQuote && spreadPct > 0.2) reasons.push(`spread is ${pct(spreadPct, 0)} of the quoted price`);
  if (!Number.isFinite(market.endMs)) reasons.push('no resolution date');
  else if (market.endMs - nowMs < config.minMinutesToResolution * 60_000) {
    reasons.push('resolves too soon to manage a position');
  }
  return { ok: reasons.length === 0, reasons, spreadPct };
}

export function runScout(universe, { config, nowMs }) {
  const markets = Array.isArray(universe?.markets) ? universe.markets : [];
  const stats = categoryStats(markets);
  const scored = [];
  const excluded = { quality: 0, data: 0, low_signal: 0, invalid: 0 };
  const dataGaps = { missing_price: 0, missing_volume: 0, missing_history: 0 };

  for (const market of markets) {
    if (!Number.isFinite(market.price) || market.price <= 0 || market.price >= 1) {
      excluded.invalid += 1;
      dataGaps.missing_price += 1;
      continue;
    }
    const quality = describeMarketQuality(market, config, nowMs);
    if (!quality.ok) {
      excluded.quality += 1;
      continue;
    }
    if (!market.volume24h) dataGaps.missing_volume += 1;

    const cat = stats.get(market.category) || stats.get('other');
    const zMove1h = cat ? robustZ(Math.abs(market.move1h), cat.absMoves1h) : 0;
    const zMove24h = cat ? robustZ(Math.abs(market.move24h), cat.absMoves24h) : 0;
    const zVolume = cat ? robustZ(Math.log1p(Math.max(market.volume24h, 0)), cat.logVolumes) : 0;
    const volumeRatio = cat && cat.medianVolume > 0 ? market.volume24h / cat.medianVolume : 1;

    const reasons = [];
    let score = 0;

    if (zMove1h > 2) {
      score += Math.min(24, 9 * zMove1h);
      reasons.push(`1h move ${pct(Math.abs(market.move1h), 1)} is ${zMove1h.toFixed(1)}σ vs its category`);
    } else if (Math.abs(market.move1h) >= 0.05) {
      score += 6;
      reasons.push(`1h move ${pct(Math.abs(market.move1h), 1)} above the 5% activity band`);
    }
    if (zMove24h > 2) {
      score += Math.min(20, 7 * zMove24h);
      reasons.push(`24h move ${pct(Math.abs(market.move24h), 1)} is ${zMove24h.toFixed(1)}σ vs its category`);
    }
    if (zVolume > 2) {
      score += Math.min(22, 8 * zVolume);
      reasons.push(`24h volume ${money(market.volume24h)} is ${volumeRatio.toFixed(1)}× the category median`);
    } else if (volumeRatio > 3) {
      score += 10;
      reasons.push(`24h volume ${volumeRatio.toFixed(1)}× the category median`);
    }
    const aligned = market.move1h * market.move24h > 0 && Math.abs(market.move24h) > 0.02;
    if (aligned) {
      score += 6;
      reasons.push('1h and 24h moves point the same way');
    }
    if (market.spread > 0 && market.price > 0 && market.spread / market.price < 0.01) {
      score += 4;
      reasons.push('tight spread relative to price');
    }
    if (market.commentCount >= 100) {
      score += 3;
      reasons.push(`${market.commentCount} comments on the event`);
    }

    score = Math.round(clamp(score, 0, 100));
    if (score < 8) {
      excluded.low_signal += 1;
      continue;
    }

    scored.push({
      market,
      score,
      reasons,
      metrics: {
        move_1h: market.move1h,
        move_24h: market.move24h,
        z_move_1h: round(zMove1h, 2),
        z_move_24h: round(zMove24h, 2),
        z_volume: round(zVolume, 2),
        volume_ratio: round(volumeRatio, 2),
        spread: market.spread,
        spread_pct: round(quality.spreadPct, 4),
        liquidity: market.liquidity,
        volume_24h: market.volume24h,
        price: round(market.price, 4),
      },
    });
  }

  scored.sort((a, b) => b.score - a.score);
  const shortlist = scored.slice(0, config.shortlistSize);

  const categories = {};
  for (const [category, stat] of stats) {
    categories[category] = stat.count;
  }

  const status = markets.length < 20 ? 'needs_data' : 'complete';
  const summary = markets.length
    ? `Scanned ${markets.length} markets, ${scored.length} passed quality filters, ${shortlist.length} on the watchlist.`
    : 'No markets were supplied, so there is nothing to scan.';

  const evidence = shortlist.map(item => ({
    market_id: item.market.id,
    question: item.market.question,
    url: item.market.url,
    category: item.market.category,
    event_id: item.market.eventId,
    event_title: item.market.eventTitle,
    order_min_size: item.market.orderMinSize,
    score: item.score,
    reasons: item.reasons,
    metrics: item.metrics,
    price: round(item.market.price, 4),
    ends_at: item.market.endDate,
    source_timestamp: item.market.updatedAt,
    synthetic: item.market.synthetic === true,
    regime: item.market.demoRegime || null,
  }));

  const risks = [];
  if (status === 'needs_data') risks.push('Universe too small to scan; refusing to shortlist.');
  if (!shortlist.length) risks.push('No market produced a score above the 8-point activity floor.');
  if (dataGaps.missing_volume) risks.push(`${dataGaps.missing_volume} markets reported no 24h volume.`);
  if (markets.some(m => m.synthetic)) {
    risks.push('Universe is SYNTHETIC TEST DATA. Scores describe generated numbers, not a real market.');
  }

  return baseReport(
    'scout',
    nowMs,
    status,
    summary,
    evidence,
    risks,
    'News agent: attach dated sources to each watchlist item.',
    {
      universe_size: markets.length,
      universe_source: universe?.source || 'unknown',
      fetched_at: universe?.fetchedAt || null,
      source_note: universe?.note || '',
      scored_count: scored.length,
      shortlist: shortlist.map(item => ({
        market_id: item.market.id,
        category: item.market.category,
        score: item.score,
      })),
      excluded,
      data_gaps: dataGaps,
      categories,
      scan_is_full_universe: universe?.source === 'live' ? markets.length >= config.maxScan : true,
      methodology:
        'Robust z-scores (median/MAD) of |1h move|, |24h move| and log 24h volume against the same category. ' +
        'No forecast is produced; the list is an attention filter only.',
    },
  );
}

