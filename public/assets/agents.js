export function runCharts(scoutReport, newsReport, histories, { config, nowMs } = {}) {
  const evidence = [];
  const risks = [];
  const newsById = new Map(newsReport.evidence.map(e => [e.market_id, e]));

  for (const item of scoutReport.evidence) {
    const news = newsById.get(item.market_id);
    const series = histories?.[item.market_id];
    if (!series || !series.points?.length) {
      evidence.push({
        market_id: item.market_id,
        question: item.question,
        status: 'needs_data',
        reason: 'no price history returned for the primary token',
        timeframe: '15m bars, 24h window',
      });
      risks.push(`No price history for "${item.question}".`);
      continue;
    }

    const primary = analyseSeries(series.points, { minPoints: config.minHistoryPoints });
    if (!primary) {
      evidence.push({
        market_id: item.market_id,
        question: item.question,
        status: 'needs_data',
        reason: `only ${series.points.length} usable points; minimum is ${config.minHistoryPoints}`,
        timeframe: '15m bars, 24h window',
        data_quality: { points: series.points.length, span_hours: series.spanHours ?? null },
      });
      risks.push(`History for "${item.question}" is too short to analyse.`);
      continue;
    }

    const inversePoints = series.points.map(p => ({ t: p.t, p: round(clamp(1 - p.p, 0.001, 0.999), 4) }));
    const secondary = analyseSeries(inversePoints, { minPoints: config.minHistoryPoints });

    const conflicts = [...primary.conflicts];
    const warnings = [...primary.warnings];
    const directNews = (news?.direct_count ?? 0) >= 2;
    if (directNews && news.tone === 'cautious' && primary.trend === 'up') {
      conflicts.push('chart trend is up while two or more direct headlines read cautious');
    }
    if (directNews && news.tone === 'constructive' && primary.trend === 'down') {
      conflicts.push('chart trend is down while two or more direct headlines read constructive');
    }
    if (news?.event_risk === 'high') conflicts.push('high event risk on the calendar');

    evidence.push({
      market_id: item.market_id,
      question: item.question,
      status: 'complete',
      timeframe: '15m bars, 24h window',
      series_source: series.source || 'price history API',
      last_quote: item.price,
      primary_outcome: series.outcomes?.[0] || 'Outcome A',
      secondary_outcome: series.outcomes?.[1] || 'Outcome B',
      views: { primary, secondary },
      sparkline: series.points.filter((_, i) => i % 3 === 0).map(p => round(p.p, 4)),
      conflicts,
      warnings,
      data_quality: {
        points: primary.points,
        span_hours: primary.span_hours,
        fetched_at: series.fetchedAt || null,
      },
      news_flags: news?.flags || [],
    });
  }

  const usable = evidence.filter(e => e.status === 'complete');
  const status = usable.length ? 'complete' : 'needs_data';
  const summary = usable.length
    ? `Reviewed ${usable.length} price series. ${usable.filter(e => e.views.primary.trend !== 'range').length} show a directional trend; ${usable.filter(e => e.conflicts.length).length} carry conflicting signals.`
    : 'No usable price series, so no chart review is possible.';

  return baseReport(
    'charts',
    nowMs,
    status,
    summary,
    evidence,
    risks,
    'Strategy agent: build one rule-based plan per market, or return WAIT.',
    {
      reviewed: usable.length,
      needs_data: evidence.length - usable.length,
      methodology:
        '24h of 15-minute closes. Trend from a linear fit in probability points per hour vs average bar range. ' +
        'Support/resistance are clustered swing pivots with at least two touches. ' +
        'The secondary view is the exact inverse of the primary series, so both outcomes are analysed the same way.',
      conflicts_total: usable.reduce((sum, e) => sum + e.conflicts.length, 0),
      warnings_total: usable.reduce((sum, e) => sum + e.warnings.length, 0),
    },
  );
}

