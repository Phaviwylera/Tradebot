const REPORT_STATUS = new Set(['complete', 'needs_data', 'rejected']);

export function validateReport(report) {
  const errors = [];
  if (!report || typeof report !== 'object') return { ok: false, errors: ['report is not an object'] };
  if (!report.agent) errors.push('missing agent');
  if (!report.timestamp_utc || !Number.isFinite(Date.parse(report.timestamp_utc))) errors.push('missing or invalid timestamp_utc');
  if (!REPORT_STATUS.has(report.status)) errors.push(`invalid status: ${report.status}`);
  if (typeof report.summary !== 'string' || !report.summary.trim()) errors.push('missing summary');
  if (!Array.isArray(report.evidence)) errors.push('evidence must be an array');
  if (!Array.isArray(report.risks)) errors.push('risks must be an array');
  if (typeof report.next_step !== 'string') errors.push('missing next_step');
  if (report.agent === 'boss') {
    const allowed = Object.values(BOSS_DECISIONS);
    if (!allowed.includes(report.meta?.decision)) errors.push(`boss decision must be one of ${allowed.join(', ')}`);
  }
  return { ok: errors.length === 0, errors };
}

export function summariseConfig(config) {
  return [
    `paper mode: ${config.mode === 'paper' && !config.allowLiveOrders ? 'ON' : 'OFF'}`,
    `scan cap: ${config.maxScan} markets`,
    `bankroll: ${money(config.bankroll)}`,
    `max ${config.maxPositions} positions / ${config.maxTotalExposurePct}% exposure / ${config.maxPositionRiskPct}% risk per trade`,
    `min liquidity ${money(config.minLiquidity)}, max spread ${config.maxSpread}`,
    `min net R:R ${config.minNetRR}, stop cap ${config.maxStopDistance}`,
  ].join(' · ');
}

