function linregSlope(values) {
  const n = values.length;
  if (n < 2) return 0;
  const meanX = (n - 1) / 2;
  const meanY = values.reduce((a, b) => a + b, 0) / n;
  let num = 0;
  let den = 0;
  for (let i = 0; i < n; i += 1) {
    num += (i - meanX) * (values[i] - meanY);
    den += (i - meanX) ** 2;
  }
  return den === 0 ? 0 : num / den;
}

function clusterLevels(points, lookback = 2) {
  const clusters = new Map();
  for (let i = lookback; i < points.length - lookback; i += 1) {
    const value = points[i].p;
    let isHigh = true;
    let isLow = true;
    for (let j = i - lookback; j <= i + lookback; j += 1) {
      if (j === i) continue;
      if (points[j].p > value) isHigh = false;
      if (points[j].p < value) isLow = false;
    }
    if (!isHigh && !isLow) continue;
    const key = Math.round(value / 0.005);
    const existing = clusters.get(key);
    if (existing) {
      existing.touches += 1;
      existing.sum += value;
      existing.level = existing.sum / existing.touches;
      existing.kind = existing.kind === (isHigh ? 'resistance' : 'support')
        ? existing.kind
        : 'either';
    } else {
      clusters.set(key, {
        level: value,
        sum: value,
        touches: 1,
        kind: isHigh ? 'resistance' : 'support',
      });
    }
  }
  return [...clusters.values()]
    .map(c => ({ level: round(c.level, 4), touches: c.touches, kind: c.kind }))
    .sort((a, b) => a.level - b.level);
}

/**
 * Describe one probability series without predicting it.
 * Returns null when there is not enough data to say anything.
 */
export function analyseSeries(points, { minPoints = 8 } = {}) {
  const clean = (points || []).filter(p => Number.isFinite(p.p) && Number.isFinite(p.t));
  if (clean.length < minPoints) return null;

  const values = clean.map(p => p.p);
  const last = values[values.length - 1];
  const spanHours = Math.max((clean[clean.length - 1].t - clean[0].t) / 3_600_000, 1e-6);
  const perPointHours = spanHours / (clean.length - 1);

  const slope24 = linregSlope(values) / perPointHours; // per hour, in probability points
  const last4 = values.slice(-4);
  const momentum1h = last4.length >= 2 ? last - last4[0] : 0;
  const last12 = values.slice(-12);
  const slope3h = last12.length >= 3
    ? (linregSlope(last12) / perPointHours) * 1
    : slope24;

  const diffs = values.slice(1).map((v, i) => Math.abs(v - values[i]));
  const atr = diffs.length ? diffs.reduce((a, b) => a + b, 0) / diffs.length : 0;
  const atrPct = last > 0 ? atr / last : 0;

  const windowMin = Math.min(...values);
  const windowMax = Math.max(...values);
  const rangePos = windowMax > windowMin ? (last - windowMin) / (windowMax - windowMin) : 0.5;
  const changePct = values[0] > 0 ? (last - values[0]) / values[0] : 0;

  const clusters = clusterLevels(clean);
  const strong = clusters.filter(c => c.touches >= 2);
  const supports = strong.filter(c => c.level <= last * 1.002).sort((a, b) => b.level - a.level);
  const resistances = strong.filter(c => c.level >= last * 0.998).sort((a, b) => a.level - b.level);

  const prior = values.slice(0, Math.max(1, values.length - 4));
  const priorMax = Math.max(...prior);
  const priorMin = Math.min(...prior);
  let structureBreak = null;
  if (last > priorMax + atr * 0.5) structureBreak = 'up';
  else if (last < priorMin - atr * 0.5) structureBreak = 'down';

  const trend = slope24 > atr * 1.2 && slope24 > 0
    ? 'up'
    : slope24 < -atr * 1.2 && slope24 < 0
      ? 'down'
      : 'range';

  const conflicts = [];
  const warnings = [];
  if (trend === 'up' && momentum1h < -atr) conflicts.push('daily trend up but last hour falling');
  if (trend === 'down' && momentum1h > atr) conflicts.push('daily trend down but last hour rising');
  if (trend === 'range' && structureBreak) conflicts.push(`range-bound series with a ${structureBreak} structure break`);
  if (trend === 'up' && rangePos > 0.97) warnings.push('uptrend is extended at the top of its range');
  if (trend === 'down' && rangePos < 0.03) warnings.push('downtrend is extended at the bottom of its range');
  if (atrPct > 0.12) warnings.push(`average bar range is ${pct(atrPct, 1)} of price, which is unusually noisy`);
  if (points.length < 40) warnings.push(`only ${points.length} bars in the window`);

  const activity = values.length > 1
    ? values.slice(1).filter((v, i) => v !== values[i]).length / (values.length - 1)
    : 0;

  const recent = values.slice(-8);
  const recentMean = recent.reduce((a, b) => a + b, 0) / recent.length;
  const stretch = atr > 0 ? (last - recentMean) / atr : 0;
  const extendedUp = rangePos > 0.96 && stretch > 1.5;

  return {
    points: values.length,
    span_hours: round(spanHours, 1),
    last: round(last, 4),
    change_pct: round(changePct, 4),
    slope_per_hour: round(slope24, 5),
    slope_3h: round(slope3h, 5),
    momentum_1h: round(momentum1h, 4),
    atr: round(atr, 4),
    atr_pct: round(atrPct, 4),
    window_min: round(windowMin, 4),
    window_max: round(windowMax, 4),
    prior_high: round(priorMax, 4),
    prior_low: round(priorMin, 4),
    range_position: round(rangePos, 3),
    structure_break: structureBreak,
    trend,
    activity: round(activity, 3),
    recent_low: round(Math.min(...recent), 4),
    recent_high: round(Math.max(...recent), 4),
    stretch: round(stretch, 2),
    extended_up: extendedUp,
    levels: {
      support: supports.slice(0, 2).map(l => l.level),
      resistance: resistances.slice(0, 2).map(l => l.level),
      strong_support: supports[0] || null,
      strong_resistance: resistances[0] || null,
      all_strong: strong.slice(0, 6),
    },
    conflicts,
    warnings,
  };
}

